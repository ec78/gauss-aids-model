<#
.SYNOPSIS
  Phase Q0 analyzer. Reads results\*.csv written by run_q0.ps1 and writes
  results\analysis.md, results\endpoint_summary.csv,
  results\element_summary.csv and results\profile_summary.csv. Purely
  descriptive: no test, interval or standard error is computed. See
  PROTOCOL.md ("Analysis").
#>
param([string]$ResultsDir = "")

$ErrorActionPreference = "Stop"
$inv = [System.Globalization.CultureInfo]::InvariantCulture
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$rd = if ($ResultsDir) { $ResultsDir } else { Join-Path $here "results" }

# ---------------------------------------------------------------- frozen constants
$PHI = -12
$FLAT_LOSS = 0.1        # descriptive: slice/profile loss below this = "flat"
$MARKER_LOSS = 1.92     # descriptive scale marker only (half of 3.84); NOT a test
$FLAT_EIG = 1e-3        # -Hessian eigenvalue (LL per (ln q)^2) below this = flat direction
$STEP_REL_TOL = 1e-3    # Hessian step agreement: max|eig1-eig2| <= this x max(1, max eig)
$LOAD_MIN = 0.3         # eigenvector loading reported as "dominant"

function D($s) { if ($null -eq $s -or $s -eq "" -or $s -eq ".") { return [double]::NaN }; return [double]::Parse($s, $inv) }
function F($x, [string]$fmt = "G4") { if ([double]::IsNaN($x)) { return "n/a" }; return $x.ToString($fmt, $inv) }
function Load([string]$n) { $p = Join-Path $rd $n; if (Test-Path $p) { return @(Import-Csv $p) } else { return @() } }

$fits = Load "fits.csv"; $best = Load "best.csv"; $starts = Load "starts.csv"; $elems = Load "elements.csv"
$points = Load "points.csv"; $slices = Load "slices.csv"; $heig = Load "heig.csv"; $hint = Load "hint.csv"
$corr = Load "corr.csv"; $prof = Load "profiles.csv"; $jobs = Load "jobs.csv"
$hvecRaw = if (Test-Path (Join-Path $rd "hvec.csv")) { @(Get-Content (Join-Path $rd "hvec.csv") | Select-Object -Skip 1) } else { @() }
$profQRaw = if (Test-Path (Join-Path $rd "profile_q.csv")) { @(Get-Content (Join-Path $rd "profile_q.csv") | Select-Object -Skip 1) } else { @() }

$eps = @($best | ForEach-Object { $_.endpoint })
$md = New-Object System.Collections.Generic.List[string]
$md.Add("# Phase Q0 analysis (generated by analyze_q0.ps1)")
$md.Add("")
$md.Add("Descriptive only. Loss = LL(qhat) - LL(point), total log-likelihood units. Slices hold every other Q element at qhat (fixed paths); profiles reoptimize the other elements (true profiles). Thresholds: flat loss < $FLAT_LOSS; scale marker $MARKER_LOSS (half of 3.84) is a reference value only, not a test; flat Hessian direction: eigenvalue of -H in ln q < $FLAT_EIG. No chi-square inference, interval, standard error or identification proof is implied, least of all at a variance boundary.")
$md.Add("")
$epRows = @(); $elRows = @(); $prRows = @()
$pointNames = @{ 1 = "qhat"; 2 = "true Q"; 3 = "shipped start"; 4 = "floor (all)"; 5 = "qhat floored"; 6 = "boundary elems at qRef" }
$groupNames = @{ 1 = "alpha"; 2 = "gamma"; 3 = "beta" }

foreach ($ep in $eps) {
    $tobs = [int]([regex]::Match($ep, '-t(\d+)-').Groups[1].Value)
    $tol = 1e-6 * $tobs
    $llhat = D ($best | Where-Object endpoint -eq $ep).llhat
    $el = @($elems | Where-Object endpoint -eq $ep)
    $k = $el.Count
    $bndIdx = @($el | Where-Object { (D $_.boundary) -eq 1 } | ForEach-Object { [int](D $_.j) })
    $md.Add("## $ep")
    $md.Add("")
    # --- starts
    $md.Add("### Starts (sensitivity)")
    $md.Add("")
    $md.Add("| start (x shipped) | rc | iters | LL - best | boundary count | max abs dlog10 q vs qhat (non-boundary) | Phase C exact |")
    $md.Add("|---|---|---|---|---|---|---|")
    $fe = @($fits | Where-Object endpoint -eq $ep)
    $se = @($starts | Where-Object endpoint -eq $ep)
    $maxStartGap = 0.0; $maxStartDlog = 0.0; $allRc0 = $true
    for ($i = 0; $i -lt $se.Count; $i++) {
        $f = $fe[$i]; $s = $se[$i]
        if ((D $f.rc) -ne 0) { $allRc0 = $false }
        $gap = D $s.ll_minus_best; $dl = D $s.max_dlog10_nonbnd
        if ([math]::Abs($gap) -gt $maxStartGap) { $maxStartGap = [math]::Abs($gap) }
        if ($dl -gt $maxStartDlog) { $maxStartDlog = $dl }
        $md.Add("| $($f.qmult) | $(F (D $f.rc) 'G3') | $(F (D $f.iters) 'G5') | $(F $gap) | $(F (D $s.nboundary) 'G3') | $(F $dl) | $($f.phasec_exact) |")
    }
    $md.Add("")
    # --- points
    $md.Add("### Special points")
    $md.Add("")
    $md.Add("| point | LL | loss |")
    $md.Add("|---|---|---|")
    $pe = @($points | Where-Object endpoint -eq $ep)
    $pl = @{}
    foreach ($p in $pe) { $c = [int](D $p.code); $pl[$c] = D $p.loss; $md.Add("| $($pointNames[$c]) | $(F (D $p.ll) 'F4') | $(F (D $p.loss)) |") }
    $md.Add("")
    # --- elements
    $sl = @($slices | Where-Object endpoint -eq $ep)
    $md.Add("### Elements: individual fixed-path slices (others at qhat)")
    $md.Add("")
    $md.Add("| j | group | qhat/qRef | boundary | loss at floor | loss at qRef | min loss on grid (c at min) | max loss c in [floor, qRef] | loss at 100 qRef | class |")
    $md.Add("|---|---|---|---|---|---|---|---|---|---|")
    $nFlatFloor = 0; $nUnderMarker = 0; $nImprove = 0
    foreach ($e in $el) {
        $j = [int](D $e.j)
        $rows = @($sl | Where-Object { (D $_.kind) -eq 3 -and [int](D $_.idx) -eq $j })
        $lf = D ($rows | Where-Object { (D $_.log10c) -eq $PHI }).loss
        $l0 = D ($rows | Where-Object { (D $_.log10c) -eq 0 }).loss
        $l2 = D ($rows | Where-Object { (D $_.log10c) -eq 2 }).loss
        $mn = $rows | Sort-Object { D $_.loss } | Select-Object -First 1
        $mxLow = ($rows | Where-Object { (D $_.log10c) -le 0 } | ForEach-Object { D $_.loss } | Measure-Object -Maximum).Maximum
        $cls = if ($lf -lt $FLAT_LOSS) { "flat to floor" } elseif ($lf -lt $MARKER_LOSS) { "shallow to floor" } else { "floor costly" }
        if ($lf -lt $FLAT_LOSS) { $nFlatFloor++ }
        if ($lf -lt $MARKER_LOSS) { $nUnderMarker++ }
        if ((D $mn.loss) -lt -$tol) { $nImprove++; $cls += "; slice improves LL" }
        $elRows += [pscustomobject]@{ endpoint = $ep; j = $j; group = $groupNames[[int](D $e.group)]; qhat = $e.qhat; qref = $e.qref; qhat_over_qref = $e.qhat_over_qref; boundary = (D $e.boundary); loss_floor = $lf; loss_qref = $l0; min_loss = (D $mn.loss); min_loss_log10c = (D $mn.log10c); max_loss_floor_to_qref = $mxLow; loss_100qref = $l2; class = $cls }
        $md.Add("| $j | $($groupNames[[int](D $e.group)]) | $(F (D $e.qhat_over_qref)) | $(F (D $e.boundary) 'G1') | $(F $lf) | $(F $l0) | $(F (D $mn.loss)) ($(F (D $mn.log10c) 'G3')) | $(F $mxLow) | $(F $l2) | $cls |")
    }
    $md.Add("")
    # --- rays
    $j1 = @($sl | Where-Object { (D $_.kind) -eq 1 })
    $r2 = @($sl | Where-Object { (D $_.kind) -eq 2 })
    $rbest = $r2 | Sort-Object { D $_.loss } | Select-Object -First 1
    $md.Add("### Joint fixed-path slices")
    $md.Add("")
    $md.Add("- Ray q = c qhat, loss by log10 c: " + (($j1 | ForEach-Object { "$(F (D $_.log10c) 'G3'): $(F (D $_.loss))" }) -join "; "))
    $md.Add("- Ray q = c qRef (common reference shape), loss by log10 c: " + (($r2 | ForEach-Object { "$(F (D $_.log10c) 'G3'): $(F (D $_.loss))" }) -join "; ") + ". Best on this ray: loss $(F (D $rbest.loss)) at log10 c = $(F (D $rbest.log10c) 'G3').")
    $md.Add("")
    # --- grouped slices vs profiles
    $md.Add("### Grouped: fixed-path slice vs true profile (group at 10^c qRef)")
    $md.Add("")
    $md.Add("| group | log10 c | slice loss | profile loss | start a rc/iters | start b rc/iters | |prof a - prof b| | prof a - slice | profile > qhat + tol | nuisance sums / qhat sums (other groups, best start) |")
    $md.Add("|---|---|---|---|---|---|---|---|---|---|")
    $pe = @($prof | Where-Object endpoint -eq $ep)
    $qhatVec = @($el | ForEach-Object { D $_.qhat })
    $grpOf = @($el | ForEach-Object { [int](D $_.group) })
    $nProfCapped = 0; $nProfExceed = 0; $maxProfStartGap = 0.0; $minProfMinusSlice = [double]::PositiveInfinity; $sliceMismatch = 0
    foreach ($g in 1..3) {
        foreach ($c in (@($pe | Where-Object { (D $_.group) -eq $g } | ForEach-Object { D $_.log10c }) | Select-Object -Unique)) {
            $rr = @($pe | Where-Object { (D $_.group) -eq $g -and (D $_.log10c) -eq $c })
            $ra = $rr | Where-Object { (D $_.start) -eq 1 } | Select-Object -First 1
            $rb = $rr | Where-Object { (D $_.start) -eq 2 } | Select-Object -First 1
            $sliceL = D ($sl | Where-Object { (D $_.kind) -eq 4 -and (D $_.idx) -eq $g -and (D $_.log10c) -eq $c }).loss
            if ([math]::Abs(($llhat - (D $ra.llslice)) - $sliceL) -gt 1e-9) { $sliceMismatch++ }
            $bestR = $rr | Sort-Object { - (D $_.llprof) } | Select-Object -First 1
            $profL = $llhat - (D $bestR.llprof)
            $gapAB = if ($rb) { [math]::Abs((D $ra.llprof) - (D $rb.llprof)) } else { [double]::NaN }
            if (-not [double]::IsNaN($gapAB) -and $gapAB -gt $maxProfStartGap) { $maxProfStartGap = $gapAB }
            foreach ($r in $rr) { if ((D $r.rc) -ne 0) { $nProfCapped++ } }
            $pms = D $ra.prof_minus_slice
            if ($pms -lt $minProfMinusSlice) { $minProfMinusSlice = $pms }
            $exceed = (D $bestR.llprof) -gt $llhat + $tol
            if ($exceed) { $nProfExceed++ }
            # tradeoff: other groups' Q sums at the best profile point relative to qhat
            $qline = $profQRaw | Where-Object { $v = $_ -split ','; $v[0] -eq $ep -and (D $v[1]) -eq $g -and (D $v[2]) -eq $c -and (D $v[3]) -eq (D $bestR.start) } | Select-Object -First 1
            $trade = ""
            if ($qline) {
                $qv = @(($qline -split ',')[4..(3 + $k)] | ForEach-Object { D $_ })
                $parts = foreach ($h in (1..3 | Where-Object { $_ -ne $g })) {
                    $sp = 0.0; $sh = 0.0
                    for ($i = 0; $i -lt $k; $i++) { if ($grpOf[$i] -eq $h) { $sp += $qv[$i]; $sh += $qhatVec[$i] } }
                    "$($groupNames[$h]) $(F ($sp / $sh) 'G3')"
                }
                $trade = $parts -join ", "
            }
            $rbTxt = if ($rb) { "$(F (D $rb.rc) 'G2')/$(F (D $rb.iters) 'G4')" } else { "--" }
            $prRows += [pscustomobject]@{ endpoint = $ep; group = $groupNames[$g]; log10c = $c; slice_loss = $sliceL; profile_loss = $profL; rc_a = (D $ra.rc); iters_a = (D $ra.iters); rc_b = $(if ($rb) { D $rb.rc } else { "" }); iters_b = $(if ($rb) { D $rb.iters } else { "" }); start_gap = $gapAB; prof_minus_slice_a = $pms; exceeds_qhat = $exceed; tradeoff = $trade }
            $md.Add("| $($groupNames[$g]) | $(F $c 'G3') | $(F $sliceL) | $(F $profL) | $(F (D $ra.rc) 'G2')/$(F (D $ra.iters) 'G4') | $rbTxt | $(F $gapAB) | $(F $pms) | $exceed | $trade |")
        }
    }
    $md.Add("")
    # --- Hessian
    $he1 = @($heig | Where-Object { $_.endpoint -eq $ep -and (D $_.step) -eq 1 } | ForEach-Object { D $_.eig })
    $he2 = @($heig | Where-Object { $_.endpoint -eq $ep -and (D $_.step) -eq 2 } | ForEach-Object { D $_.eig })
    $lmax = ($he1 | Measure-Object -Maximum).Maximum
    $dmax = 0.0
    for ($i = 0; $i -lt $he1.Count; $i++) { $d = [math]::Abs($he1[$i] - $he2[$i]); if ($d -gt $dmax) { $dmax = $d } }
    $stable = $dmax -le $STEP_REL_TOL * [math]::Max(1.0, $lmax)
    $nFlat = @($he1 | Where-Object { $_ -lt $FLAT_EIG }).Count
    $nNeg = @($he1 | Where-Object { $_ -lt - $FLAT_EIG }).Count
    $hi = $hint | Where-Object { $_.endpoint -eq $ep -and (D $_.step) -eq 1 } | Select-Object -First 1
    $md.Add("### Local curvature in ln q (step 1 = 0.01; step 2 = 0.03 check)")
    $md.Add("")
    $md.Add("- Eigenvalues of -H: " + (($he1 | ForEach-Object { F $_ }) -join ", ") + ".")
    $md.Add("- Flat directions (eig < $FLAT_EIG): $nFlat of $k; clearly negative (< -$FLAT_EIG): $nNeg. Step agreement max |diff| $(F $dmax) -> stable = $stable.")
    if ($hi) { $md.Add("- Interior block ($(F (D $hi.nint) 'G3') non-boundary elements): eig range $(F (D $hi.mineig)) to $(F (D $hi.maxeig)), condition $(F (D $hi.cond)).") }
    $flatAligned = 0
    $vecs = @($hvecRaw | Where-Object { $v = $_ -split ','; $v[0] -eq $ep -and (D $v[1]) -eq 1 })
    $loadTxt = @()
    for ($i = 0; $i -lt $he1.Count; $i++) {
        if ($he1[$i] -ge $FLAT_EIG) { continue }
        $v = @(($vecs[$i] -split ',')[3..(2 + $k)] | ForEach-Object { D $_ })
        $dom = @(); $mxj = 0; $mxv = 0.0
        for ($j = 0; $j -lt $k; $j++) { if ([math]::Abs($v[$j]) -ge $LOAD_MIN) { $dom += ($j + 1) }; if ([math]::Abs($v[$j]) -gt $mxv) { $mxv = [math]::Abs($v[$j]); $mxj = $j + 1 } }
        if ($bndIdx -contains $mxj) { $flatAligned++ }
        $loadTxt += "eig $(F $he1[$i]): dominant elements $($dom -join '/')"
    }
    if ($loadTxt.Count -gt 0) { $md.Add("- Flat-direction loadings (|v| >= $LOAD_MIN): " + ($loadTxt -join "; ") + ". Flat directions whose largest loading is a boundary element: $flatAligned of $nFlat.") }
    $cc = @($corr | Where-Object { $_.endpoint -eq $ep -and (D $_.step) -eq 1 } | Sort-Object { - [math]::Abs((D $_.c)) } | Select-Object -First 5)
    if ($cc.Count -gt 0) { $md.Add("- Largest interior curvature correlations (cross-parameter tradeoffs): " + (($cc | ForEach-Object { "($(F (D $_.i) 'G3'),$(F (D $_.j) 'G3')) $(F (D $_.c) 'F3')" }) -join "; ") + ".") }
    $md.Add("")
    $maxCorr = if ($cc.Count -gt 0) { [math]::Abs((D $cc[0].c)) } else { [double]::NaN }
    $epRows += [pscustomobject]@{ endpoint = $ep; k = $k; llhat = $llhat; tol = $tol; all_starts_rc0 = $allRc0; max_start_ll_gap = $maxStartGap; max_start_dlog10 = $maxStartDlog
        n_boundary = $bndIdx.Count; n_flat_to_floor = $nFlatFloor; n_floor_under_marker = $nUnderMarker; n_slice_improves = $nImprove
        loss_true = $pl[2]; loss_shipped = $pl[3]; loss_floor_all = $pl[4]; loss_qhat_floored = $pl[5]; loss_boundary_at_qref = $pl[6]
        n_flat_eig = $nFlat; n_neg_eig = $nNeg; hess_step_stable = $stable; flat_aligned_boundary = $flatAligned; max_abs_corr = $maxCorr
        n_prof_capped = $nProfCapped; n_prof_exceeds_qhat = $nProfExceed; max_prof_start_gap = $maxProfStartGap; min_prof_minus_slice = $minProfMinusSlice; slice_profile_point_mismatch = $sliceMismatch }
}

# ---------------------------------------------------------------- overview (prepended)
$ov = New-Object System.Collections.Generic.List[string]
$ov.Add("## Overview")
$ov.Add("")
$ov.Add("| endpoint | k | starts rc 0 | max start LL gap | boundary | flat to floor | floor < marker | flat eig | neg eig | Hessian stable | loss true Q | loss shipped | loss floor | profile capped | profile > qhat | max profile start gap | min prof a - slice |")
$ov.Add("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
foreach ($r in $epRows) {
    $ov.Add("| $($r.endpoint) | $($r.k) | $($r.all_starts_rc0) | $(F $r.max_start_ll_gap) | $($r.n_boundary) | $($r.n_flat_to_floor) | $($r.n_floor_under_marker) | $($r.n_flat_eig) | $($r.n_neg_eig) | $($r.hess_step_stable) | $(F $r.loss_true) | $(F $r.loss_shipped) | $(F $r.loss_floor_all) | $($r.n_prof_capped) | $($r.n_prof_exceeds_qhat) | $(F $r.max_prof_start_gap) | $(F $r.min_prof_minus_slice) |")
}
$ov.Add("")
$jt = @($jobs)
$ov.Add("Jobs: $($jt.Count); timeouts $(@($jt | Where-Object timed_out -eq 'True').Count); memory kills $(@($jt | Where-Object mem_killed -eq 'True').Count); GAUSS errors $(@($jt | Where-Object gauss_error -eq 'True').Count); peak working set max $(($jt | ForEach-Object { [double]$_.peak_ws_mb } | Measure-Object -Maximum).Maximum) MB; min free memory at job start $(($jt | ForEach-Object { D $_.free_gb_at_start } | Measure-Object -Minimum).Minimum) GB; summed job wall $(F ((($jt | ForEach-Object { D $_.wall_s } | Measure-Object -Sum).Sum) / 60) 'F1') min.")
$ov.Add("")
$out = @($md[0], $md[1], $md[2], $md[3]) + $ov + @($md | Select-Object -Skip 4)
($out -join "`n") + "`n" | Out-File -Encoding utf8 -NoNewline (Join-Path $rd "analysis.md")
$epRows | Export-Csv -NoTypeInformation -Encoding ascii (Join-Path $rd "endpoint_summary.csv")
$elRows | Export-Csv -NoTypeInformation -Encoding ascii (Join-Path $rd "element_summary.csv")
$prRows | Export-Csv -NoTypeInformation -Encoding ascii (Join-Path $rd "profile_summary.csv")
Write-Host "wrote analysis.md, endpoint_summary.csv, element_summary.csv, profile_summary.csv for $($eps.Count) endpoint(s)"
