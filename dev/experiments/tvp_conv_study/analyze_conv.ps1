<#
.SYNOPSIS
  Analyzer for the TVP convergence-correctness study. See PROTOCOL.md.
.DESCRIPTION
  Reads results\summary.csv (written by run_conv.ps1) and writes
  results\categories.csv (one row per first-run grid cell, with its
  category) and results\analysis.md (summary tables). Pure function of
  the CSV files: rerunning it reproduces the same output.

  Group = (stage, n1, tobs, seed_used, harm); its best LL is the largest
  llfit among that group's first-run cells. Categories, in order:
  TIMEOUT; ERROR; rc 0 with llfit < lltrue - tol: CONV-FAILC3; rc 0 with
  llfit < best - tol: CONV-LOCAL; other rc 0: CONV-GLOBAL; rc 2: CAPPED;
  any other rc: OTHER-RC. Anchor cells (no truth) skip the true-Q check.
#>
param([string]$ResultsDir = "")

$ErrorActionPreference = "Stop"
$inv = [System.Globalization.CultureInfo]::InvariantCulture
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$resultsDir = if ($ResultsDir) { $ResultsDir } else { Join-Path $here "results" }
$rows = @(Import-Csv (Join-Path $resultsDir "summary.csv"))

function ToD([string]$s) {
    if ($s -eq "" -or $s -eq ".") { return $null }
    return [double]::Parse($s, $inv)
}
function Fmt($v, [string]$f = "G10") { if ($null -eq $v) { return "" } return ([double]$v).ToString($f, $inv) }

$first = @($rows | Where-Object { $_.replicate -eq "r1" })
$best = @{}
foreach ($r in $first) {
    $k = "$($r.stage)|$($r.n1)|$($r.tobs)|$($r.seed_used)|$($r.harm)"
    $ll = ToD $r.llfit
    if ($null -ne $ll -and (-not $best.ContainsKey($k) -or $ll -gt $best[$k])) { $best[$k] = $ll }
}
$groupN = @{}
foreach ($r in $first) { $k = "$($r.stage)|$($r.n1)|$($r.tobs)|$($r.seed_used)|$($r.harm)"; $groupN[$k] = 1 + [int]$groupN[$k] }

$out = foreach ($r in $first) {
    $k = "$($r.stage)|$($r.n1)|$($r.tobs)|$($r.seed_used)|$($r.harm)"
    $ll = ToD $r.llfit; $lt = ToD $r.lltrue; $tol = ToD $r.tol; $rc = ToD $r.rc
    $b = if ($best.ContainsKey($k)) { $best[$k] } else { $null }
    $gapBest = if ($null -ne $ll -and $null -ne $b) { $b - $ll } else { $null }
    $gapTrue = if ($null -ne $ll -and $null -ne $lt) { $ll - $lt } else { $null }
    $c3 = if ($null -ne $gapTrue) { $gapTrue -ge (-1.0 * $tol) } else { "n/a" }
    $atBest = if ($null -ne $gapBest) { $gapBest -le $tol } else { $false }
    if ($r.timed_out -eq "True") { $cat = "TIMEOUT" }
    elseif ($r.gauss_error -eq "True" -or $null -eq $rc) { $cat = "ERROR" }
    elseif ($rc -eq 0) {
        if ($c3 -eq $false) { $cat = "CONV-FAILC3" }
        elseif (-not $atBest) { $cat = "CONV-LOCAL" }
        else { $cat = "CONV-GLOBAL" }
    }
    elseif ($rc -eq 2) { $cat = "CAPPED" }
    else { $cat = "OTHER-RC($($r.rc))" }
    [pscustomobject]@{
        cell_id = $r.cell_id; stage = $r.stage; n1 = $r.n1; tobs = $r.tobs; seed_used = $r.seed_used
        harm = $(if ($r.harm -eq "1") { "oracle" } else { "static" }); qmult = $r.qmult
        rc = $r.rc; iters = $r.iters; wall_s = $r.wall_s; s_per_iter = $r.s_per_iter
        llfit = $r.llfit; ll_best = (Fmt $b "R"); gap_best = (Fmt $gapBest "R"); lltrue = $r.lltrue; gap_true = (Fmt $gapTrue "R")
        tol = $r.tol; at_best = $atBest; c3_pass = $c3; maxgrad = $r.maxgrad; nboundary = $r.nboundary
        group_n = $groupN[$k]; category = $cat
    }
}
$out | Export-Csv -NoTypeInformation -Encoding ascii (Join-Path $resultsDir "categories.csv")

# ---------------------------------------------------------------- markdown
$md = New-Object System.Collections.Generic.List[string]
$md.Add("# Analysis output (generated by analyze_conv.ps1 -- do not edit)")
$md.Add("")
$md.Add("First-run grid cells: $($out.Count). Determinism replicates: $(@($rows | Where-Object { $_.replicate -ne 'r1' }).Count).")
$stopFile = Join-Path $resultsDir "STOP.txt"
if (Test-Path $stopFile) { $md.Add("Study halted: $((Get-Content -Raw $stopFile).Trim())") } else { $md.Add("No STOP.txt: no stop rule fired.") }
$md.Add("")
$md.Add("## Categories by arm and start")
$md.Add("")
$cats = @("CONV-GLOBAL", "CONV-LOCAL", "CONV-FAILC3", "CAPPED", "OTHER-RC", "ERROR", "TIMEOUT")
$md.Add("| stage | n1 | tobs | H | start | cells | " + ($cats -join " | ") + " |")
$md.Add("|---|---|---|---|---|---|" + ("---|" * $cats.Count))
foreach ($g in ($out | Group-Object stage, n1, tobs, harm, qmult)) {
    $f = $g.Group[0]
    $cnt = foreach ($c in $cats) { @($g.Group | Where-Object { $_.category -like "$c*" }).Count }
    $md.Add("| $($f.stage) | $($f.n1) | $($f.tobs) | $($f.harm) | $($f.qmult)x | $($g.Count) | " + ($cnt -join " | ") + " |")
}
$md.Add("")
$md.Add("## Per dataset: best-found LL and which starts reached it (within tol)")
$md.Add("")
$md.Add("| stage | n1 | tobs | seed | H | best LL | LL(true Q) | best - true | starts at best | start categories (1x / 10x / 0.1x) |")
$md.Add("|---|---|---|---|---|---|---|---|---|---|")
foreach ($g in ($out | Group-Object stage, n1, tobs, seed_used, harm)) {
    $f = $g.Group[0]
    $bt = ToD $f.ll_best; $lt = ToD $f.lltrue
    $d = if ($null -ne $bt -and $null -ne $lt) { Fmt ($bt - $lt) "F6" } else { "n/a" }
    $atb = (@($g.Group | Where-Object { $_.at_best -eq $true } | ForEach-Object { "$($_.qmult)x" }) -join ",")
    $catsS = (@("1", "10", "0.1") | ForEach-Object { $q = $_; $x = @($g.Group | Where-Object { $_.qmult -eq $q }); if ($x.Count) { $x[0].category } else { "-" } }) -join " / "
    $md.Add("| $($f.stage) | $($f.n1) | $($f.tobs) | $($f.seed_used) | $($f.harm) | $(Fmt $bt 'F6') | $(if ($null -ne $lt) { Fmt $lt 'F6' } else { 'n/a' }) | $d | $atb | $catsS |")
}
$md.Add("")
$md.Add("## Iterations, time and boundary counts by arm")
$md.Add("")
$md.Add("| stage | n1 | tobs | H | cells | iters min/median/max | CMLMT s/iter max | wall s total | max abs gradient max | boundary count mean |")
$md.Add("|---|---|---|---|---|---|---|---|---|---|")
foreach ($g in ($out | Group-Object stage, n1, tobs, harm)) {
    $f = $g.Group[0]
    $it = @($g.Group | ForEach-Object { ToD $_.iters } | Where-Object { $null -ne $_ } | Sort-Object)
    $med = if ($it.Count) { $it[[int][math]::Floor(($it.Count - 1) / 2)] } else { $null }
    $spi = @($g.Group | ForEach-Object { ToD $_.s_per_iter } | Where-Object { $null -ne $_ } | Measure-Object -Maximum).Maximum
    $wall = @($g.Group | ForEach-Object { ToD $_.wall_s } | Where-Object { $null -ne $_ } | Measure-Object -Sum).Sum
    $mg = @($g.Group | ForEach-Object { ToD $_.maxgrad } | Where-Object { $null -ne $_ } | Measure-Object -Maximum).Maximum
    $nb = @($g.Group | ForEach-Object { ToD $_.nboundary } | Where-Object { $null -ne $_ } | Measure-Object -Average).Average
    $itS = if ($it.Count) { "$($it[0]) / $med / $($it[-1])" } else { "" }
    $md.Add("| $($f.stage) | $($f.n1) | $($f.tobs) | $($f.harm) | $($g.Count) | $itS | $(Fmt $spi 'F3') | $(Fmt $wall 'F1') | $(Fmt $mg 'E2') | $(Fmt $nb 'F2') |")
}
$md.Add("")
$md.Add("## Determinism replicates")
$md.Add("")
$detFile = Join-Path $resultsDir "determinism.csv"
$det = if (Test-Path $detFile) { @(Import-Csv $detFile) } else { @() }
if ($det.Count -eq 0) { $md.Add("None run.") } else {
    $md.Add("| cell | endpoint byte-identical |"); $md.Add("|---|---|")
    foreach ($d in $det) { $md.Add("| $($d.cell_id) | $($d.endpoint_identical) |") }
}
$md | Out-File -Encoding ascii (Join-Path $resultsDir "analysis.md")
Write-Host "analysis: $($out.Count) cells; categories:"
$out | Group-Object category | Sort-Object Name | ForEach-Object { Write-Host "  $($_.Name): $($_.Count)" }
