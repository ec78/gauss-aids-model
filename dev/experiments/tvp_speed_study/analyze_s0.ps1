<#
.SYNOPSIS
  Phase S0 analyzer: results\deriv.csv, profile.csv, runs.csv, cells.csv
  -> results\analysis.md (derivative gate, endpoint equivalence, timing,
  frozen per-n1 speed classification). See PROTOCOL.md.
#>
param([string]$ResultsDir = "")
$ErrorActionPreference = "Stop"
$inv = [System.Globalization.CultureInfo]::InvariantCulture
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$res = if ($ResultsDir) { $ResultsDir } else { Join-Path $here "results" }
$SPEED_BAND = 1.10
function D([string]$s) { return [double]::Parse($s, $inv) }
function F($x, [string]$f) { return ([double]$x).ToString($f, $inv) }

$deriv = @(Import-Csv (Join-Path $res "deriv.csv"))
$prof = @(Import-Csv (Join-Path $res "profile.csv"))
$runs = @(Import-Csv (Join-Path $res "runs.csv"))
$cells = @(Import-Csv (Join-Path $res "cells.csv"))
$out = @()
$out += "# Phase S0 analysis (generated by analyze_s0.ps1)"
$out += ""
$out += "## 1. Derivative gate (analytic vs central finite differences, raw parameters)"
$out += ""
$out += "Gate per point: err(h = 1e-4 p) <= 1e-5 and relative LL difference between the gradient and plain filters <= 1e-12."
$out += ""
$out += "| dataset | point | ll_plain | dll_rel | max abs g | err h=1e-4 | err h=1e-3 | gate |"
$out += "|---|---|---|---|---|---|---|---|"
foreach ($r in $deriv) {
    $out += "| $($r.dataset) | $($r.point) | $(F (D $r.ll_plain) 'F6') | $(F (D $r.dll_rel) 'E2') | $(F (D $r.gnorm_inf) 'E3') | $(F (D $r.err_h1e4) 'E2') | $(F (D $r.err_h1e3) 'E2') | $($r.gate_ok) |"
}
$nd = @($deriv | Where-Object { $_.gate_ok -eq "True" }).Count
$out += ""
$out += "Points passing: $nd / $($deriv.Count). Largest err(h=1e-4): $(F (($deriv | ForEach-Object { D $_.err_h1e4 } | Measure-Object -Maximum).Maximum) 'E2')."
$out += ""
$out += "## 2. Per-evaluation profile at the shipped start (descriptive)"
$out += ""
$out += "| dataset | s / plain eval | s / gradient eval | gradient / plain | s / Q update |"
$out += "|---|---|---|---|---|"
foreach ($p in $prof) { $out += "| $($p.dataset) | $(F (D $p.sec_plain_eval) 'F4') | $(F (D $p.sec_grad_eval) 'F4') | $(F (D $p.grad_over_plain) 'F1') | $(F (D $p.sec_qupdate) 'F5') |" }
$out += ""
$out += "## 3. Endpoint equivalence (repetition 1 of each arm)"
$out += ""
$out += "E0 numerical arm reproduces the Phase C cell (rc, iterations, LL within tol, category); E1 same rc and category; E2 |LL_A - LL_N| <= tol; E3 all three repetitions of each arm byte-identical. Flags (reported, not gates): Q-agree max|QA-QN|/max|QN| <= 1e-3; B-agree max|bA-bN| <= 1e-5."
$out += ""
$out += "| cell | cat C / N / A | iters N / A | LL_A - LL_N | tol | dq_rel | db_abs | E0 (exact) | E1 | E2 | E3 | Q | B |"
$out += "|---|---|---|---|---|---|---|---|---|---|---|---|---|"
foreach ($c in $cells) {
    $out += "| $($c.cell_id) | $($c.cat_phaseC) / $($c.cat_N) / $($c.cat_A) | $([int](D $c.iters_N)) / $([int](D $c.iters_A)) | $(F (D $c.dll_A_minus_N) 'E2') | $(F (D $c.tol) 'E1') | $(F (D $c.dq_rel) 'E2') | $(F (D $c.db_abs) 'E2') | $($c.E0) ($($c.E0_exact)) | $($c.E1) | $($c.E2) | $($c.E3) | $($c.Q_agree) | $($c.B_agree) |"
}
$out += ""
$out += "## 4. Timing and evaluation counts (MLE call only; 3 repetitions per arm, order N A | A N | N A)"
$out += ""
$out += "Objective evaluations = updateproc calls in the MLE call (CMLMT's function, finite-difference, Hessian and line-search evaluations plus ssFitTVP's final filter pass). Gradient evaluations = gradproc calls (analytic arm only; each also evaluates the objective)."
$out += ""
$out += "| cell | obj evals N | obj evals A | grad evals A | median s N | median s A | min s N | min s A | ratio N/A (median) | s/iter N | s/iter A |"
$out += "|---|---|---|---|---|---|---|---|---|---|---|"
foreach ($c in $cells) {
    $out += "| $($c.cell_id) | $([int](D $c.nobj_N)) | $([int](D $c.nobj_A)) | $([int](D $c.ngrad_A)) | $(F (D $c.med_mle_N) 'F2') | $(F (D $c.med_mle_A) 'F2') | $(F (D $c.min_mle_N) 'F2') | $(F (D $c.min_mle_A) 'F2') | $(F (D $c.ratio_med_N_over_A) 'F3') | $(F ((D $c.med_mle_N)/(D $c.iters_N)) 'F3') | $(F ((D $c.med_mle_A)/(D $c.iters_A)) 'F3') |"
}
$out += ""
$out += "Repetition spread (max/min MLE seconds within an arm), per cell: " + (($cells | ForEach-Object {
    $id = $_.cell_id
    $n = @($runs | Where-Object { $_.cell_id -eq $id -and $_.arm -eq "N" } | ForEach-Object { D $_.mle_s })
    $a = @($runs | Where-Object { $_.cell_id -eq $id -and $_.arm -eq "A" } | ForEach-Object { D $_.mle_s })
    "$id N $(F (($n | Measure-Object -Maximum).Maximum / ($n | Measure-Object -Minimum).Minimum) 'F2') A $(F (($a | Measure-Object -Maximum).Maximum / ($a | Measure-Object -Minimum).Minimum) 'F2')"
}) -join "; ") + "."
$out += ""
$out += "## 5. Frozen per-n1 classification"
$out += ""
$out += "Only when every cell of that n1 passes E0-E3: 'analytic faster' if every median ratio N/A >= $SPEED_BAND, 'analytic slower' if every ratio <= 1/$SPEED_BAND, otherwise 'no consistent difference'. Pilot evidence on these cells only."
$out += ""
foreach ($n1 in ($cells | ForEach-Object { [int]$_.n1 } | Sort-Object -Unique)) {
    $cs = @($cells | Where-Object { [int]$_.n1 -eq $n1 })
    $pass = @($cs | Where-Object { $_.E0 -eq "True" -and $_.E1 -eq "True" -and $_.E2 -eq "True" -and $_.E3 -eq "True" }).Count -eq $cs.Count
    $rat = @($cs | ForEach-Object { D $_.ratio_med_N_over_A })
    $mn = ($rat | Measure-Object -Minimum).Minimum; $mx = ($rat | Measure-Object -Maximum).Maximum
    $cls = if (-not $pass) { "NOT CLASSIFIED (endpoint gate failed)" } elseif ($mn -ge $SPEED_BAND) { "analytic faster" } elseif ($mx -le 1.0 / $SPEED_BAND) { "analytic slower" } else { "no consistent difference" }
    $out += "- n1 = $($n1): $($cs.Count) cells, gates pass = $pass, median ratio N/A range $(F $mn 'F3')-$(F $mx 'F3') -> **$cls**"
}
$out | Out-File -Encoding utf8 (Join-Path $res "analysis.md")
Write-Host "wrote results\analysis.md"
