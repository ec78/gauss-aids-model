"""e0_rescore.py -- experiment E0 of CORRECTNESS_VALIDATION_PROTOCOL.md.

NO-SOLVER re-score of the 2,880 stored pilot endpoints (pilot_out/), using
the truth regenerated by e0_truth_dump.e (e0_out/truth_m*.csv).

Step 1 (gate): the regenerated truth must reproduce the stored error
columns EXACTLY:
  rawStructErr, rawLambdaErr, rawUErr, rawOverallErr  (from stored raw
                                                       endpoints)
  bsErr, bsErrExclU                                   (from stored bS)
  critTrue                                            (objective at truth)
Any mismatch is printed and the script stops (exit 2) before any table.

Step 2: pfErr (projection-free structural error, excl. u) for every cell,
pilot tables under pfErr, the protocol's prespecified predictions, the
borderline list, and trust-flag candidates T1-T4 for each configuration.

Run from this directory:
    python e0_rescore.py > e0_out/e0_rescore_console.txt
Writes e0_out/e0_report.md and e0_out/e0_cells_pferr.csv.
"""
import math
import os
import sys

import numpy as np
import pandas as pd

import pilot_analyze as pa

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "e0_out")
CUTS = [0.25, 0.5, 1.0, 2.0, 5.0]
NINTFULL = 2  # constant + one intercept shifter (pilot DGP)


def load_truth():
    t = {}
    for m in (0, 1):
        with open(os.path.join(OUT, f"truth_m{m}.csv")) as fh:
            for text in fh:
                v = [float("nan") if x == "." else float(x) for x in text.strip().split(",")]
                model, seed, ng, n1 = int(v[0]), int(v[1]), int(v[2]), int(v[3])
                n = n1 + 1
                tp = np.array(v[6:]).reshape((ng + 1, n), order="F")
                assert len(v) == 6 + (ng + 1) * n
                t[(model, seed)] = dict(critTrue=v[4], critStone=v[5], trueParams=tp, ng=ng, n1=n1)
    return t


def true_raw(tp, n1):
    """_directTrueRaw: rows 1:nIntFull | gamma 1:n1 | rows nIntFull+n+1:end."""
    n = n1 + 1
    return np.vstack([tp[:NINTFULL], tp[NINTFULL:NINTFULL + n1], tp[NINTFULL + n:]])


def raw_errs(raw, tr, linear):
    """Mirror of _pilotErrs on columns 1:n1."""
    n1 = raw.shape[1]
    bT = tr[:, :n1]
    nstruct = NINTFULL + n1 + 1 + (1 - linear)
    e = np.abs(raw - bT)
    struct = e[:nstruct].max()
    lam = -1.0 if linear else e[nstruct - 1].max()
    u = e[nstruct].max()
    return struct, lam, u, e.max()


def unproj(raw):
    """_diagUnproj (pilot_bs_diag.e): homogeneity row + adding-up column."""
    n1 = raw.shape[1]
    gam = raw[NINTFULL:NINTFULL + n1]
    out = np.vstack([raw[:NINTFULL], gam, -gam.sum(axis=0, keepdims=True), raw[NINTFULL + n1:]])
    out = np.hstack([out, -out.sum(axis=1, keepdims=True)])
    out[0, -1] += 1.0
    return out


def gate(df, truth):
    bad = []
    for i, r in df.iterrows():
        T = truth[(r.model, r.seed)]
        tp = T["trueParams"]
        tr = true_raw(tp, r.n1)
        s, l, u, o = raw_errs(r.raw, tr, 1 - r.model)
        checks = [("rawStructErr", s), ("rawUErr", u), ("rawOverallErr", o), ("critTrue", T["critTrue"])]
        if r.model == 1:
            checks.append(("rawLambdaErr", l))
        if r.bsOk == 1:
            checks.append(("bsErr", np.abs(r.bS - tp).max()))
            checks.append(("bsErrExclU", np.abs(r.bS[:-1] - tp[:-1]).max()))
        for name, val in checks:
            stored = r[name]
            if not (val == stored or (math.isnan(val) and math.isnan(stored))):
                bad.append((r.model, r.seed, r.method, r.start, name, stored, val))
    return bad


def add_pferr(df, truth):
    pf = []
    for _, r in df.iterrows():
        tp = truth[(r.model, r.seed)]["trueParams"]
        full = unproj(r.raw)
        pf.append(np.abs(full[:-1] - tp[:-1]).max())
    df = df.copy()
    df["pfErr"] = pf
    df["critStone"] = [truth[(m, s)]["critStone"] for m, s in zip(df.model, df.seed)]
    return df


CONFIGS = {
    "A16": [(1, range(1, 17))],
    "L1": [(2, [1])],
    "C1": [(3, [1])],
    "L1+C1": [(2, [1]), (3, [1])],
    "L16": [(2, range(1, 17))],
    "C16": [(3, range(1, 17))],
    "L16+C1": [(2, range(1, 17)), (3, [1])],
    "L16+C16": [(2, range(1, 17)), (3, range(1, 17))],
}


def select_cfg(g, parts):
    mask = np.zeros(len(g), bool)
    for m, st in parts:
        mask |= ((g.method == m) & g.start.isin(list(st))).values
    c = g[mask & g.conv.values]
    if not len(c):
        return None, c
    # same rule as pilot_analyze.select_operational: max critExact, ties -> (method, start) order
    c = c.sort_values(["method", "start"])
    best = c.loc[c.critExact.idxmax()]
    return best, c


def seed_rows(df):
    rows = []
    for (m, s), g in df.groupby(["model", "seed"]):
        for name, parts in CONFIGS.items():
            r, c = select_cfg(g, parts)
            if r is None:
                rows.append(dict(model=m, seed=s, cfg=name, conv=0))
                continue
            same = np.array([np.max(np.abs(pa.struct_rows(e) - pa.struct_rows(r.raw))) <= pa.BASIN_TOL for e in c.raw])
            other = c[~same]
            margin = (r.critExact - other.critExact.max()) if len(other) else np.inf
            nmeth = len(set(c.method[same]))
            rows.append(dict(model=m, seed=s, cfg=name, conv=len(c), selMethod=int(r.method), selStart=int(r.start),
                             pfErr=r.pfErr, rawErr=r.rawStructErr, bsErr=r.bsErr, crit=r.critExact,
                             critTrue=r.critTrue, critStone=r.critStone, support=int(same.sum()),
                             nMethodsInBasin=nmeth, margin=margin))
    return pd.DataFrame(rows)


def cls(err, cut=1.0):
    if err is None or (isinstance(err, float) and math.isnan(err)):
        return "never"
    return "correct" if err <= cut else "wrong"


def md(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    df = pa.load_cells(os.path.join(HERE, "pilot_out"))
    truth = load_truth()
    print(f"loaded {len(df)} cells, {len(truth)} truth rows")
    assert len(df) == 2880 and len(truth) == 60

    bad = gate(df, truth)
    if bad:
        print(f"TRUTH GATE: FAIL -- {len(bad)} mismatches; first 20:")
        for b in bad[:20]:
            print("  MISMATCH model %d seed %d method %d start %d %s stored %r regenerated %r" % b)
        sys.exit(2)
    nchk = int(len(df) * 5 + (df.model == 1).sum() + 2 * (df.bsOk == 1).sum())
    print(f"TRUTH GATE: PASS -- {nchk} stored values reproduced exactly "
          "(rawStructErr, rawUErr, rawOverallErr, critTrue for all 2,880 cells; rawLambdaErr for 1,440 "
          f"QUAIDS cells; bsErr and bsErrExclU for the {int((df.bsOk == 1).sum())} cells with bsOk=1)")

    df = add_pferr(df, truth)
    # pfErr formula check: on symmetry-fallback cells the pilot's bS was unprojected
    fb = df[(df.bsSymValid != 1) & (df.bsOk == 1)]
    dmax = (fb.pfErr - fb.bsErrExclU).abs().max()
    print(f"PFERR FORMULA CHECK: {len(fb)} symmetry-fallback cells, max |pfErr - bsErrExclU| = {dmax:.3g}")
    pf_ok = dmax <= 1e-9
    print("PFERR FORMULA CHECK:", "PASS" if pf_ok else "FAIL")
    if not pf_ok:
        sys.exit(3)
    keep = [c for c in df.columns if c not in ("raw", "bS")]
    df[keep].to_csv(os.path.join(OUT, "e0_cells_pferr.csv"), index=False)

    t = seed_rows(df)
    L = ["# E0 re-score report (no solver)", "",
         "Generated by `python e0_rescore.py` from `pilot_out/` cells and the regenerated truth in `e0_out/`. "
         "Seeds 1-30 are DEVELOPMENT data; nothing here is confirmatory.", ""]
    L.append(f"**Truth gate: PASS.** {nchk} stored values reproduced exactly from the regenerated truth "
             "(rawStructErr, rawUErr, rawOverallErr and critTrue on all 2,880 cells; rawLambdaErr on 1,440 QUAIDS "
             f"cells; bsErr and bsErrExclU on the {int((df.bsOk == 1).sum())} cells with a bS). "
             f"**pfErr formula check: PASS** ({len(fb)} symmetry-fallback cells, max |pfErr − bsErrExclU| = {dmax:.3g}).")
    L.append("")

    # ---- 1. classes per configuration under each metric
    L.append("## 1. Selected-endpoint classes (never / wrong / correct at cutoff 1)")
    L.append("")
    rows = []
    for m in (0, 1):
        for name in CONFIGS:
            x = t[(t.model == m) & (t.cfg == name)]
            def nwc(col):
                c = [cls(v) for v in x[col]]
                return f"{c.count('never')}/{c.count('wrong')}/{c.count('correct')}"
            def thr(col):
                return " / ".join(str(int((x[col] <= k).sum())) for k in CUTS)
            rows.append([pa.MODELS[m], name, nwc("pfErr"), nwc("rawErr"), nwc("bsErr"), thr("pfErr"), thr("rawErr")])
    L.append(md(["model", "config", "pfErr n/w/c", "raw n/w/c", "bS n/w/c (pilot primary)",
                 "pfErr ≤ .25/.5/1/2/5", "raw ≤ .25/.5/1/2/5"], rows))
    L.append("")

    # ---- 2. predictions
    L.append("## 2. Prespecified predictions (written in the draft protocol before E0 ran)")
    L.append("")
    preds = []
    def count(m, name, col):
        x = t[(t.model == m) & (t.cfg == name)]
        return int((x[col] <= 1).sum())
    for m, name in ((0, "L16"), (0, "C16"), (1, "L16"), (1, "C16")):
        a, b = count(m, name, "pfErr"), count(m, name, "rawErr")
        preds.append([f"{pa.MODELS[m]} {name}: pfErr count == raw count", f"{a} vs {b}", "HELD" if a == b else "FAILED"])
    for m in (0, 1):
        a, b = count(m, "A16", "pfErr"), count(m, "A16", "rawErr")
        preds.append([f"{pa.MODELS[m]} A16: pfErr count within ±2 of raw", f"{a} vs {b}", "HELD" if abs(a - b) <= 2 else "FAILED"])
    L.append(md(["prediction", "observed", "result"], preds))
    L.append("")

    # ---- 3. disagreements and borderline
    L.append("## 3. Seeds where pfErr and raw classes differ, and borderline selected endpoints (pfErr in (0.25, 2])")
    L.append("")
    rows = []
    for _, r in t[t.conv > 0].iterrows():
        dis = cls(r.pfErr) != cls(r.rawErr)
        border = 0.25 < r.pfErr <= 2
        if dis or border:
            rows.append([pa.MODELS[r.model], r.seed, r.cfg, f"{pa.METHODS[int(r.selMethod)]} s{int(r.selStart)}",
                         f"{r.pfErr:.3f}", f"{r.rawErr:.3f}", f"{r.bsErr:.3f}",
                         ("class differs; " if dis else "") + ("borderline" if border else "")])
    L.append(md(["model", "seed", "config", "selected", "pfErr", "raw", "bS", "note"], rows) if rows else "None.")
    L.append("")
    # per-cell distribution of pfErr / rawErr for converged direct cells
    conv = df[df.conv & df.method.isin([2, 3])]
    ratio = (conv.pfErr / conv.rawStructErr)
    L.append(f"All {len(conv)} genuinely converged direct-method cells: pfErr/rawStructErr ratio min {ratio.min():.2f}, "
             f"median {ratio.median():.2f}, max {ratio.max():.2f}. Converged cells with raw ≤ 1 but pfErr > 1: "
             f"{int(((conv.rawStructErr <= 1) & (conv.pfErr > 1)).sum())}; raw > 1 but pfErr ≤ 1: "
             f"{int(((conv.rawStructErr > 1) & (conv.pfErr <= 1)).sum())}.")
    a = df[df.conv & (df.method == 1)]
    ra = a.pfErr / a.rawStructErr
    L.append(f"Converged Anderson cells ({len(a)}): ratio min {ra.min():.2f}, median {ra.median():.2f}, max {ra.max():.2f}; "
             f"raw ≤ 1 but pfErr > 1: {int(((a.rawStructErr <= 1) & (a.pfErr > 1)).sum())}; "
             f"raw > 1 but pfErr ≤ 1: {int(((a.rawStructErr > 1) & (a.pfErr <= 1)).sum())}.")
    L.append("")

    # ---- 4. trust flags
    L.append("## 4. Trust-flag candidates (truth-free), evaluated on pfErr classes")
    L.append("")
    L.append("Silent failure = selected endpoint wrong (pfErr > 1) AND flagged trusted. Coverage = trusted correct / all correct. "
             "Selection rule for the flag (§5 of the protocol): zero silent failures in EVERY configuration, including A16, "
             "with coverage ≥ 80% in every configuration.")
    L.append("")
    flags = {
        "T0 converged (baseline)": lambda r: True,
        "T1 support ≥ 2": lambda r: r.support >= 2,
        "T2 basin reached by ≥ 2 methods": lambda r: r.nMethodsInBasin >= 2,
    }
    for d in (0, 1, 2, 5):
        flags[f"T3 crit ≥ critStone − {d}"] = (lambda d: lambda r: r.crit >= r.critStone - d)(d)
    for D in (0.01, 0.1, 0.5, 1.0):
        flags[f"T4 margin ≥ {D} and T3(0)"] = (lambda D: lambda r: r.margin >= D and r.crit >= r.critStone)(D)
    rows = []
    summary = {}
    for fname, f in flags.items():
        worst_silent, worst_cov = 0, 1.0
        cells = []
        for m in (0, 1):
            for name in ("A16", "L16", "C16", "L16+C1", "L16+C16"):
                x = t[(t.model == m) & (t.cfg == name) & (t.conv > 0)]
                tr = x.apply(f, axis=1) if len(x) else pd.Series(dtype=bool)
                wrong = x.pfErr > 1
                silent = int((tr & wrong).sum())
                corr = ~wrong
                cov = (tr & corr).sum() / max(1, corr.sum())
                worst_silent = max(worst_silent, silent)
                worst_cov = min(worst_cov, cov)
                cells.append(f"{silent}/{int(wrong.sum())}, {cov:.0%}")
        summary[fname] = (worst_silent, worst_cov)
        rows.append([fname] + cells + [worst_silent, f"{worst_cov:.0%}",
                                       "MEETS RULE" if worst_silent == 0 and worst_cov >= .8 else "no"])
    hdr = ["flag"] + [f"{pa.MODELS[m]} {n}" for m in (0, 1) for n in ("A16", "L16", "C16", "L16+C1", "L16+C16")] + \
          ["max silent", "min coverage", "verdict"]
    L.append("Each cell: silent failures / wrong selected, coverage of correct.")
    L.append("")
    L.append(md(hdr, rows))
    L.append("")
    meets = [k for k, (s, c) in summary.items() if s == 0 and c >= .8]
    L.append("Flags meeting the prespecified selection rule: " + (", ".join(meets) if meets else "**none**") + ".")
    L.append("")
    # wrong selected endpoints, with flag inputs
    L.append("Wrong selected endpoints (pfErr > 1) in the direct-method configurations, with flag inputs:")
    L.append("")
    rows = []
    for _, r in t[(t.conv > 0) & (t.pfErr > 1) & (t.cfg != "A16")].iterrows():
        rows.append([pa.MODELS[r.model], r.seed, r.cfg, f"{pa.METHODS[int(r.selMethod)]} s{int(r.selStart)}", f"{r.pfErr:.3g}",
                     f"{r.crit:.4f}", f"{r.critStone:.4f}", int(r.support), int(r.nMethodsInBasin),
                     "inf" if r.margin == np.inf else f"{r.margin:.3g}"])
    L.append(md(["model", "seed", "config", "selected", "pfErr", "crit", "critStone", "support",
                 "methods in basin", "margin to next basin"], rows) if rows else "None.")
    L.append("")
    st = pd.DataFrame([dict(model=m, seed=sd, critStone=v["critStone"]) for (m, sd), v in sorted(truth.items())])
    L.append("critStone (objective at the Stone/LA-AIDS start), per model: " +
             "; ".join(f"{pa.MODELS[m]} min {st[st.model == m].critStone.min():.2f}, median "
                       f"{st[st.model == m].critStone.median():.2f}, max {st[st.model == m].critStone.max():.2f}"
                       for m in (0, 1)) + ".")
    nanS = st[st.critStone.isna()]
    l1 = df[(df.method == 2) & (df.start == 1) & (df.status == 3)]
    rc3 = sorted(zip(l1.model, l1.seed))
    L.append("Cross-check: cold-LM Stone-start cells with retcode 3 (infeasible start): " +
             ", ".join(f"{pa.MODELS[m]} {sd}" for m, sd in rc3) + " -- " +
             ("IDENTICAL to the missing-critStone list." if rc3 == sorted(zip(nanS.model, nanS.seed))
              else "MISMATCH with the missing-critStone list."))
    L.append("Seeds whose Stone start is INFEASIBLE at homotopy 1 (critStone missing): " +
             (", ".join(f"{pa.MODELS[m]} {s}" for m, s in zip(nanS.model, nanS.seed)) or "none") +
             ". T3/T4 compare against critStone; a missing critStone makes the comparison false, so any "
             "'catch' T3/T4 make on these seeds is an artifact of the missing value, not a plausibility signal.")
    L.append("")

    with open(os.path.join(OUT, "e0_report.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
